-- Pricing and date overrides used by the admin Manage Fleet > P&D surface.
-- The table is deliberately separate from listings so changing availability or
-- a seasonal rate never overwrites the public catalogue record.

create table if not exists public.listing_pricing_rules (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings(id) on delete cascade,
  rule_type text not null check (rule_type in ('default', 'date')),
  valid_from date,
  valid_to date,
  weekday_price numeric(12, 2),
  weekend_price numeric(12, 2),
  price numeric(12, 2),
  is_blocked boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint listing_pricing_rules_range_check check (
    (rule_type = 'default'
      and valid_from is null
      and valid_to is null
      and is_blocked = false
      and (weekday_price is not null or weekend_price is not null))
    or
    (rule_type = 'date'
      and valid_from is not null
      and valid_to is not null
      and valid_from <= valid_to
      and (is_blocked = true or price is not null))
  ),
  constraint listing_pricing_rules_positive_prices check (
    (weekday_price is null or weekday_price > 0)
    and (weekend_price is null or weekend_price > 0)
    and (price is null or price > 0)
  )
);

create unique index if not exists listing_pricing_rules_default_uq
  on public.listing_pricing_rules (listing_id)
  where rule_type = 'default';

create unique index if not exists listing_pricing_rules_date_range_uq
  on public.listing_pricing_rules (listing_id, valid_from, valid_to)
  where rule_type = 'date';

create index if not exists listing_pricing_rules_lookup_idx
  on public.listing_pricing_rules (listing_id, valid_from, valid_to);

create or replace function public.set_listing_pricing_rules_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists listing_pricing_rules_updated_at on public.listing_pricing_rules;
create trigger listing_pricing_rules_updated_at
before update on public.listing_pricing_rules
for each row execute function public.set_listing_pricing_rules_updated_at();

alter table public.listing_pricing_rules enable row level security;

drop policy if exists "Public can read listing pricing rules" on public.listing_pricing_rules;
create policy "Public can read listing pricing rules"
on public.listing_pricing_rules
for select
to anon, authenticated
using (true);

drop policy if exists "Admins can insert listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can insert listing pricing rules"
on public.listing_pricing_rules
for insert
to authenticated
with check (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

drop policy if exists "Admins can update listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can update listing pricing rules"
on public.listing_pricing_rules
for update
to authenticated
using (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
))
with check (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

drop policy if exists "Admins can delete listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can delete listing pricing rules"
on public.listing_pricing_rules
for delete
to authenticated
using (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

revoke all on table public.listing_pricing_rules from anon, authenticated;
grant select on public.listing_pricing_rules to anon, authenticated;
grant insert, update, delete on public.listing_pricing_rules to authenticated;
do $$
declare
  pricing_sequence regclass := pg_get_serial_sequence('public.listing_pricing_rules', 'id');
begin
  if pricing_sequence is not null then
    execute format('revoke all on sequence %s from anon, authenticated', pricing_sequence);
    execute format('grant usage, select on sequence %s to authenticated', pricing_sequence);
  end if;
end
$$;

