-- Repair migration for projects where an older/partial
-- public.listing_pricing_rules table already exists.
--
-- CREATE TABLE IF NOT EXISTS does not alter an existing table. In that case
-- the original pricing migration can stop at its first index because columns
-- such as rule_type are absent. This migration adds the required columns and
-- then repeats the remaining idempotent setup. It does not delete records.

alter table public.listing_pricing_rules add column if not exists id bigint generated by default as identity;
alter table public.listing_pricing_rules add column if not exists listing_id bigint;
alter table public.listing_pricing_rules add column if not exists rule_type text;
alter table public.listing_pricing_rules add column if not exists valid_from date;
alter table public.listing_pricing_rules add column if not exists valid_to date;
alter table public.listing_pricing_rules add column if not exists weekday_price numeric(12, 2);
alter table public.listing_pricing_rules add column if not exists weekend_price numeric(12, 2);
alter table public.listing_pricing_rules add column if not exists price numeric(12, 2);
alter table public.listing_pricing_rules add column if not exists is_blocked boolean default false;
alter table public.listing_pricing_rules add column if not exists created_by uuid;
alter table public.listing_pricing_rules add column if not exists created_at timestamptz default timezone('utc', now());
alter table public.listing_pricing_rules add column if not exists updated_at timestamptz default timezone('utc', now());

update public.listing_pricing_rules
set rule_type = case
  when coalesce(is_blocked, false) or price is not null or valid_from is not null or valid_to is not null then 'date'
  else 'default'
end
where rule_type is null;

update public.listing_pricing_rules
set is_blocked = false
where is_blocked is null;

update public.listing_pricing_rules
set created_at = timezone('utc', now())
where created_at is null;

update public.listing_pricing_rules
set updated_at = timezone('utc', now())
where updated_at is null;

alter table public.listing_pricing_rules alter column is_blocked set default false;
alter table public.listing_pricing_rules alter column created_at set default timezone('utc', now());
alter table public.listing_pricing_rules alter column updated_at set default timezone('utc', now());
alter table public.listing_pricing_rules alter column rule_type set not null;
alter table public.listing_pricing_rules alter column is_blocked set not null;
alter table public.listing_pricing_rules alter column created_at set not null;
alter table public.listing_pricing_rules alter column updated_at set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.listing_pricing_rules'::regclass
      and conname = 'listing_pricing_rules_range_check'
  ) then
    alter table public.listing_pricing_rules
      add constraint listing_pricing_rules_range_check check (
        (rule_type = 'default'
          and valid_from is null
          and valid_to is null
          and coalesce(is_blocked, false) = false
          and (weekday_price is not null or weekend_price is not null))
        or
        (rule_type = 'date'
          and valid_from is not null
          and valid_to is not null
          and valid_from <= valid_to
          and (coalesce(is_blocked, false) = true or price is not null))
      ) not valid;
  end if;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.listing_pricing_rules'::regclass
      and conname = 'listing_pricing_rules_positive_prices'
  ) then
    alter table public.listing_pricing_rules
      add constraint listing_pricing_rules_positive_prices check (
        (weekday_price is null or weekday_price > 0)
        and (weekend_price is null or weekend_price > 0)
        and (price is null or price > 0)
      ) not valid;
  end if;
end
$$;

create unique index if not exists listing_pricing_rules_default_uq
  on public.listing_pricing_rules (listing_id)
  where rule_type = 'default';

create unique index if not exists listing_pricing_rules_date_range_uq
  on public.listing_pricing_rules (listing_id, valid_from, valid_to)
  where rule_type = 'date';

create index if not exists listing_pricing_rules_lookup_idx
  on public.listing_pricing_rules (listing_id, valid_from, valid_to);

create or replace function public.set_listing_pricing_rules_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists listing_pricing_rules_updated_at on public.listing_pricing_rules;
create trigger listing_pricing_rules_updated_at
before update on public.listing_pricing_rules
for each row execute function public.set_listing_pricing_rules_updated_at();

alter table public.listing_pricing_rules enable row level security;

drop policy if exists "Public can read listing pricing rules" on public.listing_pricing_rules;
create policy "Public can read listing pricing rules"
on public.listing_pricing_rules
for select
to anon, authenticated
using (true);

drop policy if exists "Admins can insert listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can insert listing pricing rules"
on public.listing_pricing_rules
for insert
to authenticated
with check (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

drop policy if exists "Admins can update listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can update listing pricing rules"
on public.listing_pricing_rules
for update
to authenticated
using (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
))
with check (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

drop policy if exists "Admins can delete listing pricing rules" on public.listing_pricing_rules;
create policy "Admins can delete listing pricing rules"
on public.listing_pricing_rules
for delete
to authenticated
using (exists (
  select 1 from public.admin_users au
  where au.user_id = (select auth.uid())
));

revoke all on table public.listing_pricing_rules from anon, authenticated;
grant select on public.listing_pricing_rules to anon, authenticated;
grant insert, update, delete on public.listing_pricing_rules to authenticated;

do $$
declare
  pricing_sequence regclass := pg_get_serial_sequence('public.listing_pricing_rules', 'id');
begin
  if pricing_sequence is not null then
    execute format('revoke all on sequence %s from anon, authenticated', pricing_sequence);
    execute format('grant usage, select on sequence %s to authenticated', pricing_sequence);
  end if;
end
$$;

notify pgrst, 'reload schema';
